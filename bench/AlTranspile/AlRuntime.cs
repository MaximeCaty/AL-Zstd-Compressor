using System.Text;

namespace AlGen;

/*
    Runtime for C# generated by al2cs.py : AL value semantics (1-based Text / arrays with bound checks, checked Integer)
    and stubs for the platform codeunits used by the codecs (DotNet_StreamReader / Writer / Encoding, Temp Blob, NavApp).
    Text holds Latin-1 chars (char code = byte), as the AL codecs do.
*/
public struct ALChar
{
    public readonly int V;
    public ALChar(int v) { V = v; }
    public static implicit operator int(ALChar c) => c.V;
    public static implicit operator ALChar(int v) => new ALChar(v);
    public static bool operator ==(ALChar a, string b) => b.Length == 1 && a.V == b[0];
    public static bool operator !=(ALChar a, string b) => !(a == b);
    public static bool operator ==(ALChar a, ALChar b) => a.V == b.V;
    public static bool operator !=(ALChar a, ALChar b) => a.V != b.V;
    public override bool Equals(object o) => o is ALChar c && c.V == V;
    public override int GetHashCode() => V;
}

public struct ALText
{
    string s;
    public ALText(string v) { s = v; }
    public string S => s ?? "";
    public static implicit operator ALText(string v) => new ALText(v);
    public static ALText operator +(ALText a, ALText b) => new ALText(a.S + b.S);
    public static bool operator ==(ALText a, ALText b) => string.CompareOrdinal(a.S, b.S) == 0;
    public static bool operator !=(ALText a, ALText b) => !(a == b);
    public override bool Equals(object o) => o is ALText t && t == this;
    public override int GetHashCode() => S.GetHashCode();
    public override string ToString() => S;
    public int Length => S.Length;
    public ALChar this[long i]
    {
        get { if (i < 1 || i > S.Length) throw new ALError($"Text index {i} out of range 1..{S.Length}"); return S[(int)i - 1]; }
        set { if (i < 1 || i > S.Length) throw new ALError($"Text index {i} out of range"); var c = S.ToCharArray(); c[i - 1] = (char)value.V; s = new string(c); }
    }
    public ALText Substring(long start, long len)
    {
        if (start < 1 || len < 0 || start - 1 + len > S.Length) throw new ALError($"Substring({start}, {len}) out of range, length {S.Length}");
        return S.Substring((int)start - 1, (int)len);
    }
    public ALText Substring(long start)
    {
        if (start < 1 || start - 1 > S.Length) throw new ALError($"Substring({start}) out of range");
        return S.Substring((int)start - 1);
    }
    public ALText PadRight(long n, ALChar c) => S.PadRight((int)n, (char)c.V);
    public ALList<ALText> Split(ALText sep)
    {
        var l = new ALList<ALText>();
        foreach (var x in S.Split(sep.S)) l.Add(x);
        return l;
    }
}

public sealed class ALError : Exception { public ALError(string m) : base(m) { } }

public sealed class ALArray<T> : IEnumerable<T>
{
    readonly T[] a; readonly int n;
    public ALArray(int size) { n = size; a = new T[size + 1]; }
    public T this[long i]
    {
        get { if (i < 1 || i > n) throw new ALError($"array index {i} out of range 1..{n}"); return a[i]; }
        set { if (i < 1 || i > n) throw new ALError($"array index {i} out of range 1..{n}"); a[i] = value; }
    }
    public void Clear() => Array.Clear(a);
    public IEnumerator<T> GetEnumerator() => a.Skip(1).GetEnumerator();
    System.Collections.IEnumerator System.Collections.IEnumerable.GetEnumerator() => GetEnumerator();
}

public sealed class ALList<T> : List<T>
{
    public T Get(long i) { if (i < 1 || i > base.Count) throw new ALError("list index"); return this[(int)i - 1]; }
    public new int Count() => base.Count;
}

public sealed class ALTextBuilder
{
    readonly StringBuilder b = new();
    public long Appends;
    public void Append(ALText t) { b.Append(t.S); Appends++; }
    public ALText ToText() => b.ToString();
    public ALText ToText(long start, long len)
    {
        if (start < 1 || len < 0 || start - 1 + len > b.Length) throw new ALError($"ToText({start}, {len}) out of range {b.Length}");
        return b.ToString((int)start - 1, (int)len);
    }
    public int Length() => b.Length;
    public void Remove(long start, long count) => b.Remove((int)start - 1, (int)count);
    public void Clear() => b.Clear();
}

public static class ALRt
{
    public static int I(long v) => checked((int)v);
    public static long L(long v) => v;
    public static ALChar C(long v) => new ALChar(checked((int)v));
    public static byte B(long v) => checked((byte)v);
    public static ALText T(ALText v) => v;
    public static int StrLen(ALText t) => t.Length;
    public static int EvalInt(ALText t) => int.Parse(t.S);
    public static void Error(ALText t) => throw new ALError(t.S);
}

public static class Latin1Text
{
    public static string FromBytes(byte[] b, int off, int n) { var c = new char[n]; for (int i = 0; i < n; i++) c[i] = (char)b[off + i]; return new string(c); }
    public static byte[] ToBytes(string s) { var r = new byte[s.Length]; for (int i = 0; i < s.Length; i++) r[i] = checked((byte)s[i]); return r; }
}

public sealed class ALInStream
{
    public byte[] Data = Array.Empty<byte>(); public int Pos;
    public static ALInStream Of(byte[] d) => new ALInStream { Data = d };
}
public sealed class ALOutStream
{
    public MemoryStream Buf = new();
    public void Write(byte b) => Buf.WriteByte(b);
}
public sealed class DotNet_Encoding { public void ISO88591() { } public void Clear() { } }
public sealed class DotNet_StreamReader
{
    ALInStream src;
    public void StreamReader(ALInStream s, DotNet_Encoding e) { src = s; }
    public ALText ReadToEnd() { var t = Latin1Text.FromBytes(src.Data, src.Pos, src.Data.Length - src.Pos); src.Pos = src.Data.Length; return t; }
    public void Clear() { }
}
public sealed class DotNet_StreamWriter
{
    ALOutStream dst;
    public void StreamWriter(ALOutStream s, DotNet_Encoding e) { dst = s; }
    public void Write(ALText t) { var b = Latin1Text.ToBytes(t.S); dst.Buf.Write(b); }
    public void Flush() { }
    public void Clear() { }
}
public sealed class Temp_Blob
{
    readonly MemoryStream m = new();
    public void CreateOutStream(ALOutStream o) { o.Buf = m; }
    public void CreateInStream(ALInStream i) { i.Data = m.ToArray(); i.Pos = 0; }
    public void Clear() { }
}
public static class NavApp
{
    public static string ResourceFolder = "";
    public static bool GetResource(ALText name, ALInStream s)
    {
        var p = Path.Combine(ResourceFolder, name.S);
        if (!File.Exists(p)) return false;
        s.Data = File.ReadAllBytes(p); s.Pos = 0;
        return true;
    }
}
